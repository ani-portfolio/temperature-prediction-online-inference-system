"""Feature code for this project, written by the ml-feature-engineering skill.

Do not edit this file: the skill replaces it when it runs again (it refuses if this file was changed). Change the
feature settings in notebooks/06_features.ipynb instead, and put hand written features in src/custom_features.py.

Two parts, kept apart on purpose:

    build_features(df, config)       Row steps and history steps. They learn nothing from the data, so they run
                                     once on every row, including the test rows. History steps (lags and rolling
                                     windows) must run on the full timeline in date order, so the test rows can
                                     see their past.
    make_preprocessor(kind, config)  Learned steps (imputing, encoding, scaling) as an unfitted sklearn pipeline.
                                     It must be fitted on training rows only: inside each CV fold during tuning,
                                     and on the whole training set for the final model. kind is "linear" (one hot
                                     encoding and scaling, for linear models) or "tree" (ordinal codes, no scaling,
                                     for tree models). High cardinality columns use sklearn's TargetEncoder in both,
                                     which also cross fits inside its own fit.

The config lives in ml_spec.yaml under features.config (load_config reads it).
"""

from __future__ import annotations

import os

import numpy as np
import pandas as pd

CONFIG_KEYS = {
    "numeric": [],             # numeric columns used as they are
    "categorical": [],         # low cardinality text or code columns
    "high_cardinality": [],    # many distinct values: TargetEncoder
    "date_parts": {},          # {date column: [year, month, week, dayofweek, dayofyear, day, quarter, is_weekend]}
    "days_since": [],          # [{column, reference}]: days from column to reference (the prediction date)
    "log": [],                 # columns to add as log1p(x), for skewed amounts
    "ratios": [],              # [{name, numerator, denominator}]
    "lags": [],                # [{column, days: [..], by: entity column or null}]
    "rolling": [],             # [{column, windows: [days], stats: [mean, sum, min, max, std], shift_days, by}]
    "custom": False,           # call src.custom_features.custom_features(df)
    "date_col": None,          # the column that orders the rows (time split or forecasting)
    "min_shift_days": 0,       # smallest lag or rolling shift allowed for any column: the forecast horizon
    "target_min_shift_days": 0,  # smallest shift for lags of the target itself: the label delay, if longer
    "target": None,
    "rare_min_frequency": 0.01,
    "exclude": [],             # columns left out of the model inputs, for example features that failed the leakage check
}
DATE_PARTS = ("year", "quarter", "month", "week", "day", "dayofweek", "dayofyear", "is_weekend")


def load_config(spec=None, root="."):
    """The feature config from the spec (a dict, or read from ml_spec.yaml in root)."""
    if spec is None:
        import yaml
        with open(os.path.join(root, "ml_spec.yaml"), encoding="utf-8") as f:
            spec = yaml.safe_load(f)
    cfg = {**CONFIG_KEYS, **(((spec or {}).get("features") or {}).get("config") or {})}
    return cfg


# ---------------------------------------------------------------- names of the columns each step makes

def _lag_name(col, days):
    return f"{col}_lag_{days}d"


def _roll_name(col, window, stat, shift):
    return f"{col}_roll_{window}d_{stat}" + (f"_shift_{shift}d" if shift else "")


def made_columns(config):
    """Every column build_features adds, as {name: (step, source column)}."""
    c = {**CONFIG_KEYS, **config}
    out = {}
    for col, parts in (c["date_parts"] or {}).items():
        for p in parts:
            out[f"{col}_{p}"] = ("date_part", col)
    for d in c["days_since"] or []:
        out[f"days_since_{d['column']}"] = ("days_since", d["column"])
    for col in c["log"] or []:
        out[f"log_{col}"] = ("log", col)
    for r in c["ratios"] or []:
        out[r["name"]] = ("ratio", f"{r['numerator']} / {r['denominator']}")
    for lag in c["lags"] or []:
        for d in lag["days"]:
            out[_lag_name(lag["column"], d)] = ("lag", lag["column"])
    for r in c["rolling"] or []:
        for w in r["windows"]:
            for s in r.get("stats") or ["mean"]:
                out[_roll_name(r["column"], w, s, r.get("shift_days") or 0)] = ("rolling", r["column"])
    return out


def feature_columns(config):
    """The model inputs: numeric (including every made column) first, then categorical, then high cardinality."""
    c = {**CONFIG_KEYS, **config}
    num = list(dict.fromkeys(list(c["numeric"]) + list(made_columns(c))))
    drop = set(c["exclude"] or [])
    return [x for x in num + list(c["categorical"]) + list(c["high_cardinality"]) if x not in drop]


# ---------------------------------------------------------------- row and history steps

def _dates(s):
    return pd.to_datetime(s, errors="coerce", format="mixed")


def _check_shift(config, column, shift, what):
    need = config.get("min_shift_days") or 0
    if column == config.get("target"):
        need = max(need, config.get("target_min_shift_days") or need)
    if shift < need:
        raise ValueError(f"{what} of {column} looks back {shift} days, but at least {need} days are needed so the "
                         "value is known at the prediction time (the horizon, or the label delay for the target).")


def _shift_by_days(df, value_col, by, date_col, days, name):
    """The value of value_col for the same entity, `days` days earlier (exact date match), as a new column."""
    keys = ([by] if by else []) + [date_col]
    past = df[keys + [value_col]].copy()
    past[date_col] = past[date_col] + pd.Timedelta(days=days)
    past = past.groupby(keys, as_index=False, sort=False)[value_col].mean().rename(columns={value_col: name})
    return df.merge(past, on=keys, how="left")


def build_features(df, config):
    """Add the row and history features to a copy of df. Run it on the full timeline (train, gap, and test rows
    together, in any order) so history features of the test rows can see the earlier rows."""
    c = {**CONFIG_KEYS, **config}
    out = df.copy()
    order = out.index
    for col, parts in (c["date_parts"] or {}).items():
        d = _dates(out[col])
        for p in parts:
            if p not in DATE_PARTS:
                raise ValueError(f"Unknown date part {p!r}. Use one of {', '.join(DATE_PARTS)}.")
            if p == "week":
                v = d.dt.isocalendar().week.astype("float")
            elif p == "is_weekend":
                v = (d.dt.dayofweek >= 5).astype("float")
            else:
                v = getattr(d.dt, p).astype("float")
            out[f"{col}_{p}"] = v
    for item in c["days_since"] or []:
        out[f"days_since_{item['column']}"] = (_dates(out[item["reference"]]) - _dates(out[item["column"]])).dt.days
    for col in c["log"] or []:
        out[f"log_{col}"] = np.log1p(pd.to_numeric(out[col], errors="coerce").clip(lower=0))
    for r in c["ratios"] or []:
        den = pd.to_numeric(out[r["denominator"]], errors="coerce")
        out[r["name"]] = pd.to_numeric(out[r["numerator"]], errors="coerce") / den.where(den != 0)

    if c["lags"] or c["rolling"]:
        date_col = c["date_col"]
        if not date_col:
            raise ValueError("Lags and rolling windows need date_col in the feature config.")
        out["_row_order"] = np.arange(len(out))
        out[date_col] = _dates(out[date_col])
        for lag in c["lags"] or []:
            for days in lag["days"]:
                _check_shift(c, lag["column"], days, "A lag")
                out = _shift_by_days(out, lag["column"], lag.get("by"), date_col, days, _lag_name(lag["column"], days))
        for r in c["rolling"] or []:
            by, col, shift = r.get("by"), r["column"], int(r.get("shift_days") or 0)
            _check_shift(c, col, shift + 0, "A rolling window")
            keys = ([by] if by else []) + [date_col]
            series = out.groupby(keys, sort=True)[col].mean().reset_index()
            for w in r["windows"]:
                for stat in r.get("stats") or ["mean"]:
                    name = _roll_name(col, w, stat, shift)
                    # Window of w days ending on each date (inclusive), computed per entity.
                    if by:
                        rolled = (series.set_index(date_col).groupby(by)[col]
                                  .rolling(f"{w}D").agg(stat).reset_index())
                    else:
                        rolled = series.set_index(date_col)[col].rolling(f"{w}D").agg(stat).reset_index()
                    rolled = rolled.rename(columns={col: "_value"})
                    # Then moved forward by shift_days, so a row only sees windows that ended shift_days earlier.
                    rolled[date_col] = rolled[date_col] + pd.Timedelta(days=shift)
                    out = out.merge(rolled.rename(columns={"_value": name}), on=keys, how="left")
        out = out.sort_values("_row_order").drop(columns="_row_order")
        out.index = order

    if c["custom"]:
        from src.custom_features import custom_features
        out = custom_features(out)
    return out


# ---------------------------------------------------------------- learned steps

def make_preprocessor(kind, config):
    """An unfitted pipeline for the model inputs. Fit it on training rows only."""
    from sklearn.compose import ColumnTransformer
    from sklearn.impute import SimpleImputer
    from sklearn.pipeline import Pipeline
    from sklearn.preprocessing import OneHotEncoder, OrdinalEncoder, StandardScaler, TargetEncoder

    c = {**CONFIG_KEYS, **config}
    inputs = feature_columns(c)
    num = [x for x in inputs if x not in c["categorical"] and x not in c["high_cardinality"]]
    cat = [x for x in c["categorical"] if x in inputs]
    high = [x for x in c["high_cardinality"] if x in inputs]
    rare = c["rare_min_frequency"] or None
    from sklearn.preprocessing import FunctionTransformer
    text = lambda: FunctionTransformer(to_text, feature_names_out="one-to-one")
    parts = []
    if kind == "linear":
        if num:
            parts.append(("numeric", Pipeline([("impute", SimpleImputer(strategy="median", add_indicator=True,
                                                                        keep_empty_features=True)),
                                               ("scale", StandardScaler())]), num))
        if cat:
            parts.append(("categorical", Pipeline([("text", text()),
                                                   ("onehot", OneHotEncoder(handle_unknown="infrequent_if_exist",
                                                                            min_frequency=rare, sparse_output=False))]), cat))
        if high:
            parts.append(("high_cardinality", Pipeline([("text", text()), ("target", TargetEncoder(random_state=0)),
                                                        ("scale", StandardScaler())]), high))
    elif kind == "tree":
        if num:
            parts.append(("numeric", "passthrough", num))   # tree models handle missing values themselves
        if cat:
            parts.append(("categorical", Pipeline([("text", text()),
                                                   ("ordinal", OrdinalEncoder(handle_unknown="use_encoded_value",
                                                                              unknown_value=-1, encoded_missing_value=-2,
                                                                              min_frequency=rare))]), cat))
        if high:
            parts.append(("high_cardinality", Pipeline([("text", text()), ("target", TargetEncoder(random_state=0))]), high))
    else:
        raise ValueError("kind must be 'linear' or 'tree'")
    pre = ColumnTransformer(parts, remainder="drop", verbose_feature_names_out=False)
    return pre.set_output(transform="pandas")


def to_text(X):
    """Categorical columns as text, with missing values as the category 'missing', so encoders see one type."""
    X = pd.DataFrame(X)
    return X.astype("object").where(X.notna(), "missing").astype(str)
